import { deflateSync } from 'node:zlib';
import { describe, expect, test } from 'vite-plus/test';
import { decodeReplayAssetData } from '../src/replay-assets';

const LIMIT = 2 * 1024 * 1024;
function encode(bytes: Uint8Array | string) {
  const data = typeof bytes === 'string' ? Buffer.from(bytes, 'utf8') : bytes;
  return { encoded: deflateSync(data).toString('base64'), byteLength: data.length };
}
function decode(value: ReturnType<typeof encode>) {
  return decodeReplayAssetData(value.encoded, value.byteLength);
}

describe('compressed Replay build assets', () => {
  test('decodes Node zlib JSON and preserves Unicode, escaped surrogates and prototype keys as data', () => {
    const value = JSON.parse(
      '{"css":"汉字🙂𝄞\\u0000","__proto__":{"polluted":true},"surrogate":"\\ud800"}',
    );
    const packed = encode(JSON.stringify(value));
    expect(decode(packed)).toEqual(value);
    expect(Object.getPrototypeOf(decode(packed))).toBe(Object.prototype);
    expect(Object.prototype).not.toHaveProperty('polluted');
  });

  test('accepts all JSON value kinds without interpreting strings as code', () => {
    for (const value of [
      null,
      false,
      123,
      'globalThis.assetExecuted = true',
      ['.chart{color:red}'],
      {},
    ]) {
      expect(decode(encode(JSON.stringify(value)))).toEqual(value);
    }
    expect(globalThis).not.toHaveProperty('assetExecuted');
  });

  test('accepts the exact UTF-8 output limit and rejects a larger declared or actual output', () => {
    const json = '"' + 'a'.repeat(LIMIT - 2) + '"';
    const packed = encode(json);
    expect((decode(packed) as string).length).toBe(LIMIT - 2);
    expect(() => decodeReplayAssetData(packed.encoded, LIMIT + 1)).toThrow();
    expect(() => decodeReplayAssetData(packed.encoded, 2)).toThrow();
    expect(() => decodeReplayAssetData(encode(json + ' ').encoded, LIMIT)).toThrow();
  });

  test('rejects invalid declared byte lengths and mismatches in either direction', () => {
    const packed = encode('"汉🙂"');
    for (const length of [
      0,
      -1,
      0.5,
      NaN,
      Infinity,
      Number.MAX_SAFE_INTEGER,
      packed.byteLength - 1,
      packed.byteLength + 1,
    ]) {
      expect(() => decodeReplayAssetData(packed.encoded, length)).toThrow();
    }
  });

  test('rejects malformed and oversized base64 before inflation', () => {
    const packed = encode('null');
    for (const data of [
      '',
      'AA==',
      '====',
      '!!!!',
      packed.encoded.slice(1),
      packed.encoded + '\\n',
      'A'.repeat(Math.ceil(LIMIT / 3) * 4 + 4),
    ]) {
      expect(() => decodeReplayAssetData(data, 4)).toThrow();
    }
    // Empty JSON string produces padding; alter only unused padding bits.
    const canonical = encode('""').encoded;
    const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
    const offset = canonical.length - (canonical.endsWith('==') ? 3 : 2);
    const noncanonical =
      canonical.slice(0, offset) +
      alphabet[alphabet.indexOf(canonical[offset]!) + 1] +
      canonical.slice(offset + 1);
    expect(canonical.endsWith('=')).toBe(true);
    expect(() => decodeReplayAssetData(noncanonical, 2)).toThrow();
  });

  test('rejects truncated data, invalid zlib headers, corrupted checksums and malformed deflate', () => {
    const packed = encode('{"style":".chart { color: red; }"}');
    const bytes = Buffer.from(packed.encoded, 'base64');
    for (const position of [0, 2, bytes.length - 1]) {
      const corrupt = Buffer.from(bytes);
      corrupt[position] ^= 0xff;
      expect(() => decodeReplayAssetData(corrupt.toString('base64'), packed.byteLength)).toThrow();
    }
    for (const length of [2, 6, bytes.length - 1]) {
      expect(() =>
        decodeReplayAssetData(bytes.subarray(0, length).toString('base64'), packed.byteLength),
      ).toThrow();
    }
  });

  test('rejects invalid UTF-8 with valid compression and checksum', () => {
    for (const invalid of [
      [0x22, 0xc0, 0xaf, 0x22], // overlong
      [0x22, 0xed, 0xa0, 0x80, 0x22], // encoded surrogate
      [0x22, 0xf4, 0x90, 0x80, 0x80, 0x22], // beyond Unicode
      [0x22, 0xe4, 0x22], // truncated
      [0x22, 0x80, 0x22], // stray continuation
      [0xef, 0xbb, 0xbf, 0x30], // BOM is not generated by JSON.stringify
    ]) {
      expect(() => decode(encode(Uint8Array.from(invalid)))).toThrow();
    }
  });

  test('rejects non-JSON rather than executing it', () => {
    for (const text of ['undefined', '({ css: "body{}" })', 'globalThis.assetExecuted = true']) {
      expect(() => decode(encode(text))).toThrow();
    }
    expect(globalThis).not.toHaveProperty('assetExecuted');
  });
});
